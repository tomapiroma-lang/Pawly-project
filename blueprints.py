def find_answer(question):
    """იპოვე პასუხი კითხვაზე რომელი საკეი-ვორდსს შეიცავს"""
    question_lower = question.lower()
    
    best_match = None
    best_score = 0
    
    for key, data in QUESTIONS_ANSWERS.items():
        score = 0
        for keyword in data["keywords"]:
            if keyword.lower() in question_lower:
                score += 1
        
        if score > best_score:
            best_score = score
            best_match = data["answer"]
    
    if best_match:
        return best_match
    else:
        return "ვერ გავიგე კითხვა 😅 დაკავშირდი ჩვენთან პირდაპირ: pawly.georgia@gmail.com ან დაწერე Instagram-ზე @pawly_dogwear!"

